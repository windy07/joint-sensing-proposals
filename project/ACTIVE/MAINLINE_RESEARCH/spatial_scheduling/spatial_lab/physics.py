def calibration_model(task,bias,total,epoch,config):
 s=sensor_list(config)[task.node];ref=reference_response(task,epoch,config,BEACON)
 if not ref['available']:raise ContractError('CALIBRATION_REFERENCE_UNAVAILABLE')
 H=np.zeros((3,total));H[0,s.range_bias]=1;H[1,s.frequency_bias]=1;H[2,s.angle_bias]=1
 z=np.array([bias[s.range_bias],bias[s.frequency_bias],bias[s.angle_bias]])
 refgain=pattern(BEACON,s,task);g=ref['snr']*refgain
 if task.role=='monostatic':g=snr(BEACON,s,task,config.get('calibration_reflector_rcs_m2',1.),epoch,config)
 if g<=0:raise ContractError('CALIBRATION_NOT_ILLUMINATED')
 beta=task.bandwidth_Hz/math.sqrt(12);tv=task.dwell_s**2/12
 R=np.diag([C0**2/(8*math.pi**2*beta**2*g)/(4 if task.role=='monostatic' else 1),1/(8*math.pi**2*tv*g),
            (s.beam_rad/(2*math.sqrt(2*g)))**2])
 return z,H,R,float(config.get('pfa_cell',1e-5)**(1/(1+g)))

def exposure_density(schedule,config):
 # Same registered isotropic energy-density proxy as the evaluator, J/m^2.
 return sum(resource(t,config)['energy_J']/(4*math.pi*float(np.sum((np.asarray(SENSORS[t.node].position)-MONITOR)**2))) for t in schedule)

def legal(schedule,view,config):
 limit=config.get('exposure_energy_density_limit_J_m2_per_cycle')
 if limit is not None:
  if not math.isfinite(limit) or limit<=0:raise ContractError('EXPOSURE_LIMIT_DOMAIN')
  if exposure_density(schedule,config)>limit:raise ContractError('EXPOSURE_DENSITY_LIMIT')
 if config.get('pace_resources',False):
  future=max(0.,(config['cycles']-view['epoch']-1)/config['cycles'])
  fraction=float(config.get('future_resource_reserve_fraction',.5))*future
  for key,initial,unit in [('energy_remaining_exact_J','rf_energy_budget_J','energy_exact_J'),('tx_remaining_exact_s','transmit_time_budget_s','tx_exact_s')]:
   remaining=Fraction(view[key]);used=sum((Fraction(resource(t,config)[unit]) for t in schedule),Fraction())
   floor=min(remaining,Fraction(str(config[initial]))*Fraction(str(fraction)))
   if remaining-used<floor:raise ContractError('FUTURE_RESOURCE_RESERVE:'+key)
 validate_numeric(schedule,view,config)
 E=sum((Fraction(resource(t,config)['energy_exact_J']) for t in schedule),Fraction())
 T=sum((Fraction(resource(t,config)['tx_exact_s']) for t in schedule),Fraction())
 if E>Fraction(view['energy_remaining_exact_J']):raise ContractError('ENERGY_EXHAUSTED')
 if T>Fraction(view['tx_remaining_exact_s']):raise ContractError('EMISSION_TIME_EXHAUSTED')
 for t in schedule:
  if not availability(view['epoch'],t.node,config) or (t.role=='direct' and not availability(view['epoch'],t.reference_node,config)):raise ContractError('NODE_UNAVAILABLE')
  if t.kind=='track' and not any(x['id']==t.item for x in view['tracks']):raise ContractError('STALE_TRACK_ID')
  if t.kind=='search' and not 0<=t.item<len(cell_list(config)):raise ContractError('SEARCH_CELL')
  if t.kind=='calibrate' and not config.get('allow_calibration',True):raise ContractError('CALIBRATION_DISABLED')
  if t.role=='bistatic' and t.kind!='calibrate' and not illumination(view['epoch'],config):raise ContractError('NO_ILLUMINATION')
 return True


def resolution_cell_count(task,config):
    """Instrument capture support times delay/Doppler resolution; one angular beam.

    The direct-reference bearing labels the same two-stream return and does not
    multiply the number of independent correlator cells. It is not a second
    independent detection search.
    """
    if task.mode=='aoa':return 1
    support=(task.pri_s-task.pulse_width_s) if task.role=='monostatic' else 2*device(config,task.node)['passive_delay_window_s']
    delay_cells=max(1,int(math.ceil(support*task.bandwidth_Hz)))
    doppler_cells=max(1,int(math.ceil(task.dwell_s/task.pri_s)))
    return delay_cells*doppler_cells


def conditional_detection_probability(pos,sensor,task,epoch,config,emission=None):
    """Conditioned on an admitted packet and its acquired common reference.

    emission=None gives the *single-capture* marginal. A multi-capture consumer
    must retain the emitter event and pass its branch value, rather than multiply
    these marginals. No packet-delivery probability enters an admitted likelihood.
    """
    f=detection_components(pos,sensor,task,epoch,config)
    e=f['emission'] if emission is None else float(emission)
    return f['receiver']*(e if task.role=='direct' else 1.)
