def availability(epoch,node,config):
 for spec in config.get('node_outages',[]):
  if spec['node']==node and spec['start']<=epoch<spec['end']:return False
 return not (node==1 and config.get('availability_gap',False) and 12<=epoch<16)

def illumination(epoch,config):
 return epoch not in config.get('illumination_off_epochs',[]) and not(config.get('illumination_gap',False) and epoch%20 in (10,11,12))

def azimuth(pos,sensor):
 d=np.asarray(pos)-sensor.position;return math.atan2(d[1],d[0])

def aim(task,view,sensor):return task.bearing_rad,task.beam_rad

def covers(pos,task,view,sensor):
 delta=np.asarray(pos)-sensor.position;r=float(np.linalg.norm(delta))
 if r<=C0*task.pulse_width_s/2 and task.role=='monostatic':return False
 if task.role=='monostatic' and r>=C0*(task.pri_s-task.pulse_width_s)/2:return False
 return any(abs(float(wrap(math.atan2(delta[1],delta[0])-a)))<=task.beam_rad/2 for a,d in task.scan)

def pattern(pos,sensor,task):
 # Gaussian power mainlobe; declared processing support is one HPBW.
 a=abs(float(wrap(azimuth(pos,sensor)-task.bearing_rad)))
 return math.exp(-4*math.log(2)*(a/task.beam_rad)**2)

def blocked(pos,sensor,config):
 # Optional line-of-sight opaque discs, same geometric test in world and predictor.
 a=np.asarray(sensor.position);p=np.asarray(pos);v=p-a
 for obstacle in config.get('opaque_discs',[]):
  c=np.asarray(obstacle['centre_m']);r=obstacle['radius_m'];s=np.clip((c-a)@v/max(v@v,1e-12),0,1)
  if np.linalg.norm(a+s*v-c)<r:return True
 return False

def snr(pos,sensor,task,rcs=1.,epoch=0,config=None):
 config=config or {};r=max(1.,float(np.linalg.norm(np.asarray(pos)-sensor.position)))
 if blocked(pos,sensor,config):return 0.
 lam=C0/task.carrier_Hz;N0=KB*sensor.temperature_K*sensor.noise_factor*sensor.loss;pat=pattern(pos,sensor,task)
 if task.role=='monostatic':
  E=resource(task,config)['energy_J'];return E*sensor.gain**2*pat**2*lam**2*rcs/((4*math.pi)**3*r**4*N0)
 if task.role=='direct':
  # External target emission power is fixed environmental/model data, never generated by policy.
  return config.get('emitter_eirp_W',.01)*task.dwell_s*sensor.gain*pat*lam**2/((4*math.pi*r)**2*N0)
 if not illumination(epoch,config) or blocked(pos,Sensor(-1,'external','passive',tuple(ILLUMINATOR),0,0),config):return 0.
 rt=max(1.,float(np.linalg.norm(np.asarray(pos)-ILLUMINATOR)))
 return config.get('illuminator_eirp_W',1e4)*task.dwell_s*sensor.gain*pat*lam**2*rcs/((4*math.pi)**3*rt**2*r**2*N0)

def reference_response(task,epoch,config,pos=None):
 d=device(config,task.node);s=sensor_list(config)[task.node]
 if task.kind=='calibrate':
  available=epoch not in config.get('calibration_reference_off_epochs',[])
  r=np.linalg.norm(BEACON-np.asarray(s.position));eirp=config.get('calibration_beacon_eirp_W',.01)
 elif task.role=='bistatic':
  available=illumination(epoch,config);r=np.linalg.norm(ILLUMINATOR-np.asarray(s.position));eirp=config.get('illuminator_eirp_W',1e4)
 elif task.role=='direct':
  available=availability(epoch,task.reference_node,config)
  r=np.linalg.norm(np.asarray(pos if pos is not None else cell_list(config)[max(0,task.item)%len(cell_list(config))])-np.asarray(SENSORS[task.reference_node].position));eirp=config.get('emitter_eirp_W',.01)
 else:return {'available':True,'snr':float('inf'),'pd':1.,'delay_variance_s2':0.,'frequency_variance_Hz2':0.}
 g=eirp*task.dwell_s*d['direct_reference_gain']*(C0/task.carrier_Hz)**2/((4*math.pi*max(r,1))**2*KB*d['temperature_K']*d['noise_factor']*d['loss'])
 # Opaque line of sight applies to both reference and surveillance legs.
 if task.kind=='calibrate':available=available and not blocked(BEACON,s,config)
 elif task.role=='bistatic':available=available and not blocked(ILLUMINATOR,s,config)
 elif task.role=='direct':available=available and not blocked(np.asarray(pos if pos is not None else cell_list(config)[max(0,task.item)%len(cell_list(config))]),SENSORS[task.reference_node],config)
 if not available:g=0.
 if g<=0:return {'available':False,'snr':0.,'pd':0.,'delay_variance_s2':None,'frequency_variance_Hz2':None}
 beta=task.bandwidth_Hz/math.sqrt(12);vtime=task.dwell_s**2/12
 return {'available':True,'snr':float(g),'pd':float(config.get('pfa_cell',1e-5)**(1/(1+g))),
  'delay_variance_s2':1/(8*math.pi**2*beta**2*g),'frequency_variance_Hz2':1/(8*math.pi**2*vtime*g)}

def detection_components(pos,sensor,task,epoch,config,rcs=1.):
 """Probability factors with the same random-event scopes as World.observe.

 Direct reference reception is emitter-specific within a capture. Bistatic
 reference acquisition is one common event for all returns in that capture.
 The direct emission Bernoulli is one per target per epoch, never per beam.
 """
 emit=float(config.get('emission_probability',.7)) if task.role=='direct' else 1.
 if not availability(epoch,sensor.id,config):return {'emission':emit,'reference':0.,'receiver':0.}
 if task.role=='direct' and not availability(epoch,task.reference_node,config):return {'emission':emit,'reference':0.,'receiver':0.}
 g=snr(pos,sensor,task,rcs,epoch,config)
 if g<=0:return {'emission':emit,'reference':0.,'receiver':0.}
 ref=reference_response(task,epoch,config,pos)
 thermal=float(config.get('pfa_cell',1e-5)**(1/(1+g)))
 return {'emission':emit,'reference':ref['pd'] if task.role=='bistatic' else 1.,
         'receiver':thermal*(ref['pd'] if task.role=='direct' else 1.)}

def detection_probability(pos,sensor,task,epoch,config,rcs=1.):
 f=detection_components(pos,sensor,task,epoch,config,rcs)
 return f['emission']*f['reference']*f['receiver']

def passive_state(state,bias,sensor,task):
 ref=SENSORS[task.reference_node] if task.role=='direct' else None
 db=bias[sensor.range_bias]-(bias[ref.range_bias] if ref else 0.)
 fb=bias[sensor.frequency_bias]-(bias[ref.frequency_bias] if ref else 0.)
 return np.r_[state,db/C0,fb,bias[sensor.angle_bias]]

def measurement(state,bias,sensor,task=None,offset_s=0.):
 x=np.asarray(state,float).copy();x[:2]+=x[2:]*offset_s
 if task is None or task.role=='monostatic':
  p=x[:2]-sensor.position;r=np.linalg.norm(p);u=p/r
  return np.array([r+bias[sensor.range_bias],math.atan2(p[1],p[0])+bias[sensor.angle_bias],u@(x[2:]-sensor.velocity)-(C0/sensor.carrier_Hz)/2*bias[sensor.frequency_bias]])
 ref=SENSORS[task.reference_node] if task.role=='direct' else None
 refstation=Station(ref.position,ref.velocity) if ref else Station(tuple(ILLUMINATOR))
 z,_=measurement_and_jacobian(passive_state(x,bias,sensor,task),Station(sensor.position,sensor.velocity),refstation,task.carrier_Hz,
  mode='direct_emitter' if ref else 'bistatic_scatter',availability=LinkAvailability(True,True,True))
 if task.mode=='aoa':return z[2:]
 if ref:
  z=np.r_[z,azimuth(x[:2],ref)+bias[ref.angle_bias]]
 return z

def jacobian(state,sensor,total,start,task=None,offset_s=0.):
 x=np.asarray(state,float).copy();x[:2]+=x[2:]*offset_s;F=np.eye(4);F[0,2]=offset_s;F[1,3]=offset_s
 if task is None or task.role=='monostatic':
  p=x[:2]-sensor.position;r=np.linalg.norm(p);u=p/r;v=x[2:]-sensor.velocity
  G=np.zeros((3,4));G[0,:2]=u;G[1,:2]=[-p[1]/r**2,p[0]/r**2];G[2,:2]=(v-u*(u@v))/r;G[2,2:]=u
  H=np.zeros((3,total));H[:,start:start+4]=G@F;H[0,sensor.range_bias]=1;H[1,sensor.angle_bias]=1;H[2,sensor.frequency_bias]=-C0/sensor.carrier_Hz/2
  return H
 ref=SENSORS[task.reference_node] if task.role=='direct' else None
 _,G=measurement_and_jacobian(np.r_[x,0.,0.,0.],Station(sensor.position,sensor.velocity),Station(ref.position,ref.velocity) if ref else Station(tuple(ILLUMINATOR)),task.carrier_Hz,
  mode='direct_emitter' if ref else 'bistatic_scatter',availability=LinkAvailability(True,True,True))
 H=np.zeros((3,total));H[:,start:start+4]=G[:,:4]@F;H[0,sensor.range_bias]=1/C0;H[1,sensor.frequency_bias]=1;H[2,sensor.angle_bias]=1
 if ref:
  H[0,ref.range_bias]=-1/C0;H[1,ref.frequency_bias]=-1
 if task.mode=='aoa':return H[2:]
 if ref:
  p=x[:2]-ref.position;r=np.linalg.norm(p);g=np.array([-p[1]/r**2,p[0]/r**2,0.,0.])@F
  H=np.vstack([H,np.zeros(total)]);H[3,start:start+4]=g;H[3,ref.angle_bias]=1
 return H

def covariance_support_reason(pos,sensor,task,epoch,config):
 """Declared support of a detected-signal covariance at a public hypothesis.

 A clutter return or a noisy inverse position need not be in this support.
 Zero physical signal and missing reference are model events; nonfinite or
 negative signal power remains a model/input error, never a discarded sample.
 """
 p=np.asarray(pos,dtype=float)
 if p.shape!=(2,) or not np.isfinite(p).all():raise ContractError('NONFINITE_MEASUREMENT_POSITION')
 g=snr(p,sensor,task,epoch=epoch,config=config)
 if not math.isfinite(g) or g<0:raise ContractError('INVALID_MEASUREMENT_SIGNAL_POWER')
 if g==0:return 'no_signal'
 if task.role!='monostatic' and task.mode!='aoa':
  ref=reference_response(task,epoch,config,p)
  if not ref['available']:return 'no_reference'
  if not math.isfinite(ref['snr']) or ref['snr']<=0:raise ContractError('INVALID_MEASUREMENT_REFERENCE_POWER')
 return None


def noise_parts(pos,sensor,task,epoch,config,rcs=1.):
 g=snr(pos,sensor,task,rcs,epoch,config)
 if not math.isfinite(g) or g<=0:raise ContractError('NO_SIGNAL_FOR_MEASUREMENT_COVARIANCE')
 beta=task.bandwidth_Hz/math.sqrt(12);tv=task.dwell_s**2/12
 # Local measurement-level Fisher-law approximation conditional on detection.
 # No fixed error floors. Steering quantization fixes the ACTUAL commanded
 # beam, not an invented independent angular measurement noise floor.
 vt=1/(8*math.pi**2*beta**2*g);vf=1/(8*math.pi**2*tv*g)
 va=(sensor.beam_rad/(2*math.sqrt(2*g)))**2
 if task.role=='monostatic':return np.diag([C0**2*vt/4,va,(C0/task.carrier_Hz)**2*vf/4]),np.zeros((3,3))
 if task.mode=='aoa':return np.array([[va]]),np.zeros((1,1))
 ref=reference_response(task,epoch,config,pos)
 if not ref['available']:raise ContractError('NO_MEASURED_REFERENCE')
 n=4 if task.role=='direct' else 3
 ref_angle_var=(device(config,task.reference_node)['beam_rad']**2/(8*ref['snr'])) if n==4 else 0.
 R=np.diag([vt,vf,va,*([ref_angle_var] if n==4 else [])]);Rc=np.zeros((n,n))
 Rc[0,0]=ref['delay_variance_s2'];Rc[1,1]=ref['frequency_variance_Hz2']
 # The direct reference here is a separate emitter signal per target; persistent
 # common oscillator errors are joint states, not independent per-target noise.
 if task.role=='direct':R+=Rc;Rc*=0
 return R,Rc

def noise_cov(pos,sensor,task,epoch,config):
 R,C=noise_parts(pos,sensor,task,epoch,config);return R+C

