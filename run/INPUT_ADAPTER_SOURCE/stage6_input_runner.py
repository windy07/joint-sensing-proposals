"""Explicit operational input adapter for the pinned, unchanged Stage6 release.

The base source digest still identifies the original files. A separate execution
profile identifies this adapter; it is written to run/model records and to each
saved checkpoint's SHA-bound .execution.json companion. Never relabel old data
or checkpoints as having been generated by this adapter.
"""
from pathlib import Path
import argparse,collections,hashlib,json,os,sys,threading,time,uuid
from ordered_input import InputStats,loader
HERE=Path(__file__).resolve().parent

def file_sha(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as stream:
        for part in iter(lambda:stream.read(1024*1024),b''):h.update(part)
    return h.hexdigest()

def assert_adapter_files(profile):
    for name,expected in profile['files'].items():
        if Path(name).name!=name or file_sha(HERE/name)!=expected:
            raise RuntimeError('INPUT_ADAPTER_CONTENT_CHANGED:'+name)

def verify_adapter(project):
    profile=json.loads((HERE/'INPUT_TRANSPORT_PROFILE.json').read_text(encoding='utf-8-sig'))
    assert_adapter_files(profile)
    project=Path(project).resolve();sys.path.insert(0,str(project))
    import stage6_server as controller
    if Path(controller.__file__).resolve()!=project/'stage6_server.py':raise RuntimeError('FOREIGN_STAGE6_CONTROLLER')
    from spatial_lab.binding import source_digest,dependency_contract
    from spatial_lab.core import digest
    if source_digest()!=profile['base_source_digest']:raise RuntimeError('INPUT_ADAPTER_BASE_SOURCE_MISMATCH')
    if dependency_contract()!=profile['dependencies']:raise RuntimeError('INPUT_ADAPTER_DEPENDENCY_MISMATCH')
    return controller,{**profile,'execution_profile_digest':digest(profile)}

def install_adapter(controller,profile,project):
    import spatial_lab.stage6_training as training
    from spatial_lab.core import read_json,write_json,atomic_save,digest
    original_perform=controller.perform;original_popen=controller.subprocess.Popen
    original_loader=training.loader;original_training_write=training.write_json;original_save=training.atomic_save
    def run_with_input(plan,out,job,device,resume):
        if job['kind']!='train':return original_perform(plan,out,job,device,resume)
        assert_adapter_files(profile)
        dest=Path(out)/'models'/job['arm']/str(job['model_seed']);dest.mkdir(parents=True,exist_ok=True)
        binding={'schema':'ain.stage6.input.execution.v1','base_source_digest':profile['base_source_digest'],
                 'execution_profile':profile,'plan_digest':digest(plan),
                 'prepared_index_sha256':file_sha(Path(out)/'prepare/INDEX.json'),
                 'validation_index_sha256':file_sha(Path(out)/'validation_prepare/INDEX.json')}
        for path in (Path(out)/'INPUT_TRANSPORT_BINDING.json',dest/'INPUT_TRANSPORT_BINDING.json'):
            if path.exists() and read_json(path)!=binding:raise RuntimeError('INPUT_EXECUTION_BINDING_CHANGED:'+str(path))
            if not path.exists():write_json(path,binding)
        for name in [*profile['files'],'INPUT_TRANSPORT_PROFILE.json']:
            src=HERE/name;target=Path(out)/'INPUT_ADAPTER_SOURCE'/name
            if target.exists() and file_sha(target)!=file_sha(src):raise RuntimeError('RECORDED_INPUT_SOURCE_CHANGED:'+name)
            if not target.exists():atomic_save(target,lambda f,src=src:f.write(src.read_bytes()))
        latest=dest/'latest.pt';attempt={'schema':'ain.stage6.input.attempt.v1','status':'RUNNING',
            'execution_profile_digest':profile['execution_profile_digest'],'started_ns':time.time_ns(),'pid':os.getpid(),
            'resume_checkpoint_sha256':file_sha(latest) if latest.exists() else None,
            'resume_checkpoint_has_execution_record':latest.with_name('latest.pt.execution.json').exists()}
        attempt_path=dest/'input_attempts'/f'{time.time_ns()}_{uuid.uuid4().hex}.json';write_json(attempt_path,attempt)
        stats=InputStats();observed={};history=collections.deque();stop=threading.Event();obs_lock=threading.Lock()
        def progress(path,obj):
            if Path(path).name=='TRAIN_RECEIPT.json':
                assert_adapter_files(profile)
                now=time.monotonic();examples=obj.get('contexts_this_attempt',0)
                history.append((now,examples))
                while len(history)>2 and history[1][0]<now-60:history.popleft()
                duration=now-history[0][0];recent=(examples-history[0][1])/duration if duration>0 else 0.
                obj={**obj,'input_transport':stats.snapshot(),'execution_profile_digest':profile['execution_profile_digest'],
                     'recent_contexts_per_s':recent,'recent_window_s':duration}
                with obs_lock:observed.update(optimizer_updates=obj.get('optimizer_updates',0),phase=obj.get('phase'),
                    receipt_updated_ns=obj.get('updated_ns'),recent_contexts_per_s=recent,recent_window_s=duration)
            return original_training_write(path,obj)
        def checkpoint_with_execution(path,writer):
            assert_adapter_files(profile)
            result=original_save(path,writer)
            path=Path(path)
            if path.name in ('latest.pt','best.pt'):
                write_json(path.with_name(path.name+'.execution.json'),{
                    'schema':'ain.stage6.checkpoint.execution.v1','checkpoint_file':path.name,'checkpoint_sha256':file_sha(path),
                    'base_source_digest':profile['base_source_digest'],'execution_profile':profile,
                    'input_binding_digest':digest(binding),'recorded_ns':time.time_ns(),
                    'prior_updates_may_use_original_transport':attempt['resume_checkpoint_sha256'] is not None})
            return result
        heartbeat_errors=[]
        def heartbeat():
            while not stop.is_set():
                try:
                    with obs_lock:current=dict(observed)
                    write_json(dest/'INPUT_PIPELINE_STATUS.json',{
                        'schema':'ain.stage6.input.progress.v1','updated_ns':time.time_ns(),
                        'execution_profile_digest':profile['execution_profile_digest'],**current,**stats.snapshot()})
                except Exception as exc:heartbeat_errors.append(repr(exc))
                stop.wait(5.)
        training.loader=lambda dataset,order,batch,workers:loader(dataset,order,batch,workers,stats)
        training.write_json=progress;training.atomic_save=checkpoint_with_execution
        thread=threading.Thread(target=heartbeat,name='radar_input_status',daemon=True);thread.start()
        try:
            result=original_perform(plan,out,job,device,resume);attempt['status']='COMPLETE';return result
        except BaseException as exc:attempt.update(status='FAILED',error=repr(exc));raise
        finally:
            stop.set();thread.join(timeout=15.)
            training.loader=original_loader;training.write_json=original_training_write;training.atomic_save=original_save
            attempt.update(finished_ns=time.time_ns(),input_statistics=stats.snapshot(),heartbeat_errors=heartbeat_errors[-3:])
            write_json(attempt_path,attempt)
    def spawn_with_adapter(command,*args,**kwargs):
        if (isinstance(command,(list,tuple)) and len(command)>5 and
            Path(str(command[4])).resolve()==Path(project).resolve()/'stage6.py' and command[5]=='worker'):
            command=[*command[:4],str(HERE/'stage6_input_runner.py'),'--transport-project',str(Path(project).resolve()),*command[5:]]
        return original_popen(command,*args,**kwargs)
    controller.perform=run_with_input;controller.subprocess.Popen=spawn_with_adapter

def main():
    ap=argparse.ArgumentParser(add_help=False)
    ap.add_argument('--transport-project',required=True);ap.add_argument('--transport-check',action='store_true')
    args,rest=ap.parse_known_args();controller,profile=verify_adapter(args.transport_project)
    if args.transport_check:
        from spatial_lab.core import read_json
        plans={str(scale):controller.check_plan(read_json(Path(args.transport_project)/'STAGE6_SERVER'/f'plan_{scale}.json')) for scale in (1280,12800)}
        print(json.dumps({'status':'INPUT_ADAPTER_CHECK_PASSED','base_source_digest':profile['base_source_digest'],
                          'execution_profile_digest':profile['execution_profile_digest'],'plans':plans,
                          'world_advances':0,'optimizer_updates':0},ensure_ascii=False));return
    install_adapter(controller,profile,args.transport_project)
    sys.argv=[str(Path(args.transport_project)/'stage6.py'),*rest];controller.main()

if __name__=='__main__':main()
